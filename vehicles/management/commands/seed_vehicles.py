def create_placeholder_image(filename: str, title: str, subtitle: str, color_hex: str) -> str:
    """Generate a clean sample banner image for seeded vehicles."""
    if not HAS_PILLOW:
        return ""

    vehicles_media_dir = os.path.join(settings.MEDIA_ROOT, "vehicles")
    os.makedirs(vehicles_media_dir, exist_ok=True)
    file_path = os.path.join(vehicles_media_dir, filename)

    if os.path.exists(file_path):
        return f"vehicles/{filename}"

    width, height = 800, 500
    img = Image.new("RGB", (width, height), color=color_hex)
    draw = ImageDraw.Draw(img)

    # Draw modern inner card rectangle
    draw.rectangle([30, 30, width - 30, height - 30], outline=(255, 255, 255), width=3)
    draw.rectangle([50, 50, width - 50, height - 50], fill=(0, 0, 0, 40))

    # Add text banner
    text_content = f"{title.upper()}\n{subtitle}\nEasy Rental Verified"
    draw.text((70, 180), text_content, fill=(255, 255, 255))

    img.save(file_path, "JPEG", quality=85)
    return f"vehicles/{filename}"


