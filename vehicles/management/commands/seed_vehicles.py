class Command(BaseCommand):
    help = "Seeds the database with a rich, realistic fleet of diverse vehicles across all vehicle types."

    def add_arguments(self, parser):
        parser.add_argument(
            "--clear",
            action="store_true",
            help="Delete existing vehicles and images before seeding.",
        )
        parser.add_argument(
            "--no-images",
            action="store_true",
            help="Skip generating sample vehicle image files.",
        )

    def handle(self, *args, **options):
        clear_old = options["clear"]
        skip_images = options["no_images"]

        if clear_old:
            self.stdout.write(self.style.WARNING("Clearing existing vehicles..."))
            Vehicle.objects.all().delete()
            self.stdout.write(self.style.SUCCESS("Existing vehicles deleted."))

        created_count = 0
        updated_count = 0

        today = date.today()
        reg_expiry = today + timedelta(days=365)
        ins_expiry = today + timedelta(days=180)

        for item in VEHICLES_SEED_DATA:
            image_file = item.pop("image_file", None)
            bg_color = item.pop("bg_color", "#2c3e50")

            reg_no = item["registration_number"]

            defaults = {
                **item,
                "registration_expiry": reg_expiry,
                "insurance_expiry": ins_expiry,
                "status": VehicleStatus.ACTIVE,
            }

            vehicle, created = Vehicle.objects.update_or_create(
                registration_number=reg_no,
                defaults=defaults,
            )

            if created:
                created_count += 1
            else:
                updated_count += 1

            # Handle primary sample image
            if not skip_images and image_file:
                image_rel_path = create_placeholder_image(
                    filename=image_file,
                    title=vehicle.name,
                    subtitle=f"{vehicle.brand} • {vehicle.get_vehicle_type_display()} • {vehicle.year}",
                    color_hex=bg_color,
                )

                if image_rel_path:
                    # Update or create the primary VehicleImage
                    VehicleImage.objects.update_or_create(
                        vehicle=vehicle,
                        is_primary=True,
                        defaults={
                            "image": image_rel_path,
                            "alt_text": f"Photo of {vehicle.name}",
                        },
                    )

        self.stdout.write(
            self.style.SUCCESS(
                f"\nSuccessfully seeded vehicles!\n"
                f"  Created: {created_count}\n"
                f"  Updated: {updated_count}\n"
                f"  Total vehicles in database: {Vehicle.objects.count()}\n"
            )
        )
